#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { keccak256 } from "viem";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "contracts/out/WalletHelperV1.sol/WalletHelperV1.json");
const outputPath = path.join(
  root,
  "packages/chain-registry/src/wallet-helper-v1-artifact.ts",
);

const artifact = JSON.parse(await readFile(sourcePath, "utf8"));
const creationCode = artifact.bytecode?.object;
const runtimeTemplate = artifact.deployedBytecode?.object;
if (
  typeof creationCode !== "string" ||
  !/^0x[0-9a-f]+$/u.test(creationCode) ||
  typeof runtimeTemplate !== "string" ||
  !/^0x[0-9a-f]+$/u.test(runtimeTemplate)
) {
  throw new Error("WalletHelperV1 Forge artifact is invalid");
}

const source =
  "// Generated by scripts/generate-p05-05-helper-artifact.mjs. Do not edit.\n" +
  `export const WALLET_HELPER_V1_CREATION_CODE = ${JSON.stringify(creationCode)} as const;\n` +
  `export const WALLET_HELPER_V1_CREATION_CODE_HASH = ${JSON.stringify(keccak256(creationCode))} as const;\n` +
  `export const WALLET_HELPER_V1_RUNTIME_TEMPLATE_HASH = ${JSON.stringify(keccak256(runtimeTemplate))} as const;\n` +
  `export const WALLET_HELPER_V1_RUNTIME_BYTES = ${(runtimeTemplate.length - 2) / 2} as const;\n`;

await writeFile(outputPath, source, "utf8");
