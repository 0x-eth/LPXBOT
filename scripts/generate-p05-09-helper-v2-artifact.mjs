#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { keccak256, toFunctionSelector, toFunctionSignature } from "viem";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "contracts/out/WalletHelperV2.sol/WalletHelperV2.json");
const outputPath = path.join(
  root,
  "packages/chain-registry/src/wallet-helper-v2-artifact.ts",
);

const artifact = JSON.parse(await readFile(sourcePath, "utf8"));
const abi = artifact.abi;
const creationCode = artifact.bytecode?.object;
const runtimeTemplate = artifact.deployedBytecode?.object;
if (
  !Array.isArray(abi) ||
  typeof creationCode !== "string" ||
  !/^0x[0-9a-f]+$/u.test(creationCode) ||
  typeof runtimeTemplate !== "string" ||
  !/^0x[0-9a-f]+$/u.test(runtimeTemplate)
) {
  throw new Error("WalletHelperV2 Forge artifact is invalid");
}

const selectors = abi
  .filter((item) => item.type === "function")
  .map((item) => {
    const signature = toFunctionSignature(item);
    return { selector: toFunctionSelector(item), signature };
  })
  .sort((left, right) => left.signature.localeCompare(right.signature));

const abiHash = `sha256:${createHash("sha256")
  .update(JSON.stringify(abi), "utf8")
  .digest("hex")}`;
const source =
  "// Generated by scripts/generate-p05-09-helper-v2-artifact.mjs. Do not edit.\n" +
  `export const WALLET_HELPER_V2_ABI = ${JSON.stringify(abi, null, 2)} as const;\n` +
  `export const WALLET_HELPER_V2_ABI_HASH = ${JSON.stringify(abiHash)} as const;\n` +
  `export const WALLET_HELPER_V2_SELECTORS = ${JSON.stringify(selectors, null, 2)} as const;\n` +
  `export const WALLET_HELPER_V2_CREATION_CODE = ${JSON.stringify(creationCode)} as const;\n` +
  `export const WALLET_HELPER_V2_CREATION_CODE_HASH = ${JSON.stringify(keccak256(creationCode))} as const;\n` +
  `export const WALLET_HELPER_V2_RUNTIME_TEMPLATE_HASH = ${JSON.stringify(keccak256(runtimeTemplate))} as const;\n` +
  `export const WALLET_HELPER_V2_RUNTIME_BYTES = ${(runtimeTemplate.length - 2) / 2} as const;\n`;

await writeFile(outputPath, source, "utf8");
